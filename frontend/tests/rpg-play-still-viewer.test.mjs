import { readFileSync } from 'node:fs'
import { test } from 'node:test'
import assert from 'node:assert/strict'

const page = readFileSync(new URL('../app/views/rpg/play.vue', import.meta.url), 'utf8')
const dossier = page.match(/<aside class="dossier">[\s\S]*?<\/aside>/)
const turn = page.match(/<article v-for="turn in session\?\.turns \|\| \[\]"[\s\S]*?<\/article>/)
const live = page.match(/<article v-if="acting" class="turn live">[\s\S]*?<\/article>/)

test('each finished turn keeps its own still under the narrative, and the dossier does not', () => {
  assert.ok(dossier, 'dossier')
  assert.doesNotMatch(dossier[0], /class="media-actions"|class="media-error"|class="still"|class="clip"|生成剧情图|生成影像/)
  assert.match(dossier[0], />此刻</)
  assert.match(dossier[0], />人物</)
  assert.match(dossier[0], />物品</)
  assert.match(dossier[0], />物料</)
  assert.match(dossier[0], /定妆和场景图还在后台补，稍后刷新可见/)
  assert.match(dossier[0], /currentScenePlate/)
  assert.match(dossier[0], /person\.image_url/)
  assert.match(dossier[0], /item\.image_url/)

  assert.ok(turn, 'turn article')
  assert.match(turn[0], /<p class="narrative">\{\{ turn\.narrative \}\}<\/p>/)
  assert.match(turn[0], /@click="illustrate\(turn\)"/)
  assert.match(turn[0], /@click="film\(turn\)"/)
  assert.match(turn[0], /imageLabel\(turn\)/)
  assert.match(turn[0], /videoLabel\(turn\)/)
  const figure = turn[0].match(/<figure v-if="turn\.image_url" class="still">[\s\S]*?<\/figure>/)
  assert.ok(figure, 'turn still figure')
  assert.match(figure[0], /class="still-open"/)
  assert.match(figure[0], /type="button"/)
  assert.match(figure[0], /openStill\(\$event, turn\.image_url, '这一幕的剧情图', 'turn-' \+ turn\.id\)/)
  assert.match(figure[0], /alt="这一幕的剧情图"/)
  assert.doesNotMatch(figure[0], /still-viewer/)
  assert.match(turn[0], /turn\.video_url/)
  assert.match(turn[0], /turn\.image_error/)
  assert.match(turn[0], /turn\.video_error/)

  assert.ok(live, 'live turn')
  assert.doesNotMatch(live[0], /illustrate|film|image_url|media-actions/)

  assert.match(page, /turn_id: turn\.id/)
  assert.match(page, /imageBusy\(turn\)/)
  assert.match(page, /videoBusy\(turn\)/)

  const style = page.slice(page.indexOf('<style'))
  const stageRule = style.match(/^\.stage \{[^}]*\}/m)
  assert.ok(stageRule, 'stage rule')
  assert.match(stageRule[0], /display:\s*flex/)
  assert.match(stageRule[0], /flex-direction:\s*column/)
  assert.match(stageRule[0], /overflow:\s*hidden/)
  const logRule = style.match(/^\.log \{[^}]*\}/m)
  assert.ok(logRule, 'log rule')
  assert.match(logRule[0], /flex:\s*1 1 auto/)
  assert.match(logRule[0], /min-height:\s*0/)
  assert.match(logRule[0], /overflow:\s*auto/)
  assert.doesNotMatch(logRule[0], /position:\s*(absolute|fixed|sticky)/)
  const dockRule = style.match(/^\.dock \{[^}]*\}/m)
  assert.ok(dockRule, 'dock rule')
  assert.match(dockRule[0], /flex:\s*none/)
  assert.match(dockRule[0], /position:\s*static/)
  assert.doesNotMatch(dockRule[0], /position:\s*(absolute|fixed|sticky)/)
  assert.match(style, /\.turn \{[^}]*flex:\s*none/)
  assert.match(style, /\.still img, \.clip \{[^}]*max-height:\s*180px[^}]*object-fit:\s*cover/)
  assert.match(style, /\.still-open \{[^}]*cursor:\s*zoom-in/)
  assert.match(style, /\.still-open:focus-visible \{/)
  assert.match(style, /\.plate-open \{[^}]*cursor:\s*zoom-in/)
})

test('clicking a turn still or a plate opens that image in the lightbox', () => {
  assert.match(page, /<Teleport to="body">/)
  assert.match(page, /class="overlay still-viewer"/)
  assert.match(page, /role="dialog"/)
  assert.match(page, /aria-modal="true"/)
  assert.match(page, /:aria-label="viewer\.alt"/)
  assert.match(page, /@click\.self="closeStill"/)
  assert.match(page, /class="still-viewer-img"/)
  assert.match(page, /:src="viewer\.src"/)
  assert.match(page, /function openStill\(/)
  assert.match(page, /function closeStill\(/)
  assert.match(page, /event\.key !== 'Escape'/)
  assert.doesNotMatch(page, /v-if="stillOpen && latest\?\.image_url"/)
  assert.doesNotMatch(page, /:src="latest\.image_url"/)

  const viewer = page.match(/<Teleport to="body">[\s\S]*?<\/Teleport>/)
  assert.ok(viewer, 'lightbox teleport')
  assert.match(viewer[0], /class="still-viewer-img"/)
  assert.match(viewer[0], /v-if="viewer"/)
  assert.doesNotMatch(viewer[0], /object-fit:\s*cover/)
  assert.doesNotMatch(viewer[0], /max-height:\s*180px/)

  const style = page.slice(page.indexOf('<style'))
  const viewerImg = style.match(/\.still-viewer-img \{[^}]*\}/)
  assert.ok(viewerImg, 'viewer image rule')
  assert.match(viewerImg[0], /object-fit:\s*contain/)
  assert.match(viewerImg[0], /max-width:\s*calc\(100vw - \(var\(--still-viewer-pad-x\) \* 2\)\)/)
  assert.match(viewerImg[0], /max-height:\s*calc\(100dvh - var\(--still-viewer-pad-top\) - var\(--still-viewer-pad-bottom\)\)/)
  assert.doesNotMatch(viewerImg[0], /object-fit:\s*cover/)
  assert.doesNotMatch(viewerImg[0], /max-height:\s*180px/)
})
